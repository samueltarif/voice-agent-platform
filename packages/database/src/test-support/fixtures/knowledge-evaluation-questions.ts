/**
 * SOMENTE TESTES (PR B1 / DEC-067): perguntas do corpus de avaliação, escritas
 * ANTES do algoritmo v2. `split`: `dev` pode orientar o desenvolvimento;
 * `holdout` só é medido (não serve para ajustar regras).
 *
 * - `mustShow`: marcadores que precisam aparecer nos 3 primeiros trechos DIRECT.
 * - `mustNotShow`: marcadores que NÃO podem aparecer em nenhum trecho DIRECT.
 * - `evidence`: false ⇒ a resposta correta é "sem evidência" (nenhum DIRECT).
 * - `aspectsNotFound`: aspecto comercial pedido sem valor explícito (só v2).
 */
export type EvaluationKind =
  'POSITIVE' | 'NEGATIVE' | 'CODE' | 'COMMERCIAL' | 'ISOLATION' | 'HOSTILE';

export interface EvaluationQuestion {
  readonly id: string;
  readonly org: 'A' | 'B';
  readonly kind: EvaluationKind;
  readonly split: 'dev' | 'holdout';
  readonly query: string;
  readonly evidence: boolean;
  readonly mustShow?: readonly string[] | undefined;
  readonly mustNotShow?: readonly string[] | undefined;
  readonly aspectsNotFound?: readonly string[] | undefined;
}

